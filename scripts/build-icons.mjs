// Builds src/components/iconData.ts from the Figma exports in public/icons.
// Re-run after re-exporting:  node scripts/build-icons.mjs
//
// Expects files named "Size=S|M|L, Type=<Name>.svg" (12 / 16 / 24 canvas).
// Keeps only <path> artwork. Figma's canvas clip groups are dropped — an
// inline <svg> already clips to its own box.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "public/icons");
const outFile = join(root, "src/components/iconData.ts");

// Figma layer name → code name
const NAME = {
  "About": "about",
  "Ai": "ai",
  "Brush": "brush",
  "Chat": "chat",
  "Check": "check",
  "Chevron": "chevron",
  "Close": "close",
  "Download": "download",
  "Help": "help",
  "Info": "info",
  "Knife": "knife",
  "Nav Close": "panel-close",
  "Nav Open": "panel-open",
  "Share": "share",
  "Up Arrow": "arrow",
  "check Default": "checkbox",
  "check Select": "checkbox-checked",
};

const attr = (tag, name) => (tag.match(new RegExp(`\\s${name}="([^"]*)"`)) || [])[1];
const color = v => (v && v !== "none" ? "currentColor" : undefined);

const icons = {};
const unknown = [];

for (const file of readdirSync(srcDir).sort()) {
  const m = file.match(/^Size=(S|M|L), Type=(.+)\.svg$/);
  if (!m) continue;
  const [, size, figmaName] = m;
  const name = NAME[figmaName];
  if (!name) { unknown.push(file); continue; }

  const svg = readFileSync(join(srcDir, file), "utf8");
  // Drop clip-path/mask definitions so their rects aren't read as artwork
  const body = svg.replace(/<defs>[\s\S]*?<\/defs>/g, "");
  const viewBox = attr(svg.match(/<svg[^>]*>/)[0], "viewBox");

  const paths = [...body.matchAll(/<path\b[^>]*\/?>/g)].map(([tag]) => {
    const p = { d: attr(tag, "d") };
    const fill = attr(tag, "fill");
    const stroke = attr(tag, "stroke");
    if (fill !== undefined) p.fill = color(fill) ?? "none";
    if (stroke) p.stroke = color(stroke);
    const sw = attr(tag, "stroke-width");
    if (stroke && sw) p.strokeWidth = Number(sw);
    if (stroke && !sw) p.strokeWidth = 1;
    const fr = attr(tag, "fill-rule");
    if (fr) p.fillRule = fr;
    const cr = attr(tag, "clip-rule");
    if (cr) p.clipRule = cr;
    const lc = attr(tag, "stroke-linecap");
    if (lc) p.strokeLinecap = lc;
    const lj = attr(tag, "stroke-linejoin");
    if (lj) p.strokeLinejoin = lj;
    return p;
  });

  (icons[name] ??= {})[size] = { viewBox, paths };
}

if (unknown.length) {
  console.error("Unmapped exports (add them to NAME):\n  " + unknown.join("\n  "));
  process.exit(1);
}

const out = `// GENERATED by scripts/build-icons.mjs from public/icons — do not edit by hand.

export type IconPath = {
  d: string;
  fill?: string;
  stroke?: string;
  strokeWidth?: number;
  fillRule?: "evenodd" | "nonzero";
  clipRule?: "evenodd" | "nonzero";
  strokeLinecap?: "round" | "butt" | "square";
  strokeLinejoin?: "round" | "miter" | "bevel";
};
export type IconMaster = { viewBox: string; paths: IconPath[] };
export type IconSizes = { S?: IconMaster; M?: IconMaster; L?: IconMaster };

export const ICONS = ${JSON.stringify(icons, null, 2)} as const satisfies Record<string, IconSizes>;

export type IconName = keyof typeof ICONS;
`;

writeFileSync(outFile, out);
const summary = Object.entries(icons).map(([n, s]) => `${n}(${Object.keys(s).join("")})`).join(" ");
console.log(`Wrote ${outFile}\n${summary}`);
